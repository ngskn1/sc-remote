// Bridge for the remote-desktop pages (host engine, manager, session windows).
const { contextBridge, ipcRenderer, webUtils } = require('electron');
const inv = (ch, ...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('remoteApp', {
  platform: process.platform,
  // host settings
  state: () => inv('remote:state'),
  setEnabled: on => inv('remote:set-enabled', on),
  setPassword: pw => inv('remote:set-password', pw),
  setAutostart: on => inv('remote:set-autostart', on),
  setKeepAwake: on => inv('remote:set-keep-awake', on),
  newId: () => inv('remote:new-id'),
  onState: cb => ipcRenderer.on('remote:state', (_e, s) => cb(s)),
  // engine
  hostConfig: () => inv('remote:host-config'),
  verify: (nonce, mac, peer, bind, extra) => inv('remote:verify', nonce, mac, peer, bind, extra),
  history: () => inv('remote:history'),
  onHistory: cb => ipcRenderer.on('remote:history-changed', () => cb()),
  serviceInfo: () => inv('remote:service-info'),
  serviceConfigure: () => inv('remote:service-configure'),
  sessionEnd: sid => inv('remote:session-end', sid),
  status: s => inv('remote:status', s),
  displays: () => inv('remote:displays'),
  selectDisplay: i => inv('remote:select-display', i),
  input: ev => ipcRenderer.send('remote:input', ev),
  onKick: cb => ipcRenderer.on('remote:kick', (_e, reason) => cb(reason)),
  onInputError: cb => ipcRenderer.on('remote:input-error', (_e, m) => cb(m)),
  // client
  connect: opts => inv('remote:connect', opts),
  saved: () => inv('remote:saved'),
  forget: id => inv('remote:forget', id),
  creds: () => inv('session:creds'),
  appInfo: () => inv('app:info'),
  setLang: l => inv('app:set-lang', l),
  openFeedback: () => inv('app:open-feedback'),
  updateInfo: () => inv('update:get'),
  updateInstall: () => inv('update:install'),
  onUpdate: cb => ipcRenderer.on('update:changed', (_e, u) => cb(u)),
  signedIn: password => inv('session:signed-in', password),
  filesDir: dir => inv('session:files-dir', dir),
  onSavedChanged: cb => ipcRenderer.on('remote:saved-changed', () => cb()),
  onClosing: cb => ipcRenderer.on('session:closing', () => cb()),
  setTitle: t => inv('session:set-title', t),
  // clipboard
  clipWatch: on => inv('clip:watch', on),
  clipSet: payload => inv('clip:set', payload),
  onClip: cb => ipcRenderer.on('clip:changed', (_e, p) => cb(p)),
  // files
  fsList: dir => inv('fs:list', dir),
  fsDownloads: () => inv('fs:downloads'),
  fsOpenRead: p => inv('fs:open-read', p),
  fsRead: (h, off, len) => inv('fs:read', h, off, len),
  fsOpenWrite: (dir, name) => inv('fs:open-write', dir, name),
  fsWrite: (h, data) => inv('fs:write', h, data),
  fsClose: (h, removePath) => inv('fs:close', h, removePath),
  fsReveal: p => inv('fs:reveal', p),
  fsWalk: paths => inv('fs:walk', paths),
  fsStage: () => inv('fs:stage'),
  fsUnique: (base, names) => inv('fs:unique', base, names),
  fsMkdirRel: (base, rel) => inv('fs:mkdir-rel', base, rel),
  fsOpenWriteRel: (base, rel) => inv('fs:open-write-rel', base, rel),
  fsJoin: (base, names) => inv('fs:join', base, names),
  pathForFile: f => { try { return webUtils.getPathForFile(f); } catch { return ''; } },
  dropFiles: (paths, x, y) => inv('remote:drop-files', paths, x, y),
  dragStart: () => ipcRenderer.send('remote:drag-start'),
  log: m => inv('remote:log', m),
  // lab edition: host side (engine)
  hostSignHello: (nonce, hostFp, clientFp) => inv('remote:host-sign-hello', nonce, hostFp, clientFp),
  verifyKey: (payload, peer) => inv('remote:verify-key', payload, peer),
  hostPolicy: () => inv('remote:host-policy'),
  auditTail: () => inv('remote:audit-tail'),
  sas: () => inv('remote:sas'),
  onDesktop: cb => ipcRenderer.on('remote:desktop', (_e, d) => cb(d)),
  onFrame: cb => ipcRenderer.on('remote:frame', (_e, f) => cb(f)),
  onPolicyChanged: cb => ipcRenderer.on('remote:policy-changed', (_e, c) => cb(c)),
  // lab edition: member side
  labMe: () => inv('lab:me'),
  labSetName: n => inv('lab:set-name', n),
  labList: () => inv('lab:labs'),
  labImportFile: () => inv('lab:import-file'),
  labImportText: t => inv('lab:import-text', t),
  labExportFile: labId => inv('lab:export-file', labId),
  labCreate: name => inv('lab:create', name),
  labUpdate: (labId, changes) => inv('lab:update', labId, changes),
  labForget: labId => inv('lab:forget', labId),
  labConnect: (labId, pc) => inv('lab:connect', labId, pc),
  labTarget: (labId, pc) => inv('lab:target', labId, pc),
  labSetPublished: (labId, pc, v) => inv('lab:set-published', labId, pc, v),
  labThisPc: () => inv('lab:this-pc'),
  labHostInfo: () => inv('lab:host-info'),
  labSavePc: (labId, pc, on) => inv('lab:save-pc', labId, pc, on),
  labRemember: (labId, pc) => inv('lab:remember', labId, pc),
  onLabChanged: cb => ipcRenderer.on('lab:changed', () => cb()),
  labHostStart: (labId, autostart) => inv('lab:host-start', labId, !!autostart),
  labHostStop: () => inv('lab:host-stop'),
  labHostAutostart: on => inv('lab:host-autostart', !!on),
  labCheckHost: (labId, pc, hello, hostFp, clientFp) => inv('lab:check-host', labId, pc, hello, hostFp, clientFp),
  labTrustHost: (labId, pc, hostKey) => inv('lab:trust-host', labId, pc, hostKey),
  labSignAuth: (labId, pc, nonce, hostFp, clientFp, purpose) => inv('lab:sign-auth', labId, pc, nonce, hostFp, clientFp, purpose),
  labVersion: labId => inv('lab:version', labId),
  labSignedPolicy: labId => inv('lab:signed-policy', labId),
  labOffer: (labId, sp) => inv('lab:offer', labId, sp),
  // banner / consent prompt pages
  promptInfo: () => inv('lab:prompt-info'),
  promptAnswer: a => ipcRenderer.send('lab:prompt-answer', a),
});
